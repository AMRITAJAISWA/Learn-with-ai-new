"use client";

import React, { useState } from "react";
import Link from "next/link";
import {
  BookOpen,
  Sparkles,
  Plus,
  Clock,
  CheckCircle2,
  ArrowRight,
  Search,
  Filter,
} from "lucide-react";
import { store, CourseData } from "@/lib/db/store";

export default function CoursesListPage() {
  const [search, setSearch] = useState("");
  const [courses, setCourses] = useState<CourseData[]>(store.courses);

  const filtered = courses.filter((c) =>
    c.title.toLowerCase().includes(search.toLowerCase()) ||
    c.description.toLowerCase().includes(search.toLowerCase())
  );

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <span className="text-xs font-bold uppercase tracking-wider text-sky-600">
            Curriculum Hub
          </span>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900">
            My Enrolled Courses
          </h1>
          <p className="text-xs text-slate-500 mt-0.5">
            Personalized learning paths dynamically generated by your AI curriculum architect.
          </p>
        </div>

        <Link
          href="/courses/new"
          className="inline-flex items-center gap-2 rounded-2xl bg-gradient-to-r from-sky-600 to-blue-600 px-5 py-3 text-xs font-bold text-white shadow-lg shadow-sky-600/20 hover:from-sky-500 hover:to-blue-500 active:scale-95 transition-all"
        >
          <Sparkles className="h-4 w-4" />
          <span>Generate New Course</span>
        </Link>
      </div>

      {/* Search Bar */}
      <div className="flex items-center gap-4">
        <div className="relative flex-1 max-w-md">
          <Search className="absolute left-3.5 top-1/2 -translate-y-1/2 h-4 w-4 text-slate-400" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search courses or topics..."
            className="w-full rounded-2xl border border-slate-200 bg-white py-2.5 pl-10 pr-4 text-xs text-slate-900 focus:border-sky-500 focus:outline-none focus:ring-2 focus:ring-sky-100"
          />
        </div>
      </div>

      {/* Course Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {filtered.map((course) => {
          const totalTopics = course.modules.reduce(
            (acc, m) => acc + m.topics.length,
            0
          );
          const completedTopics = course.modules.reduce(
            (acc, m) =>
              acc + m.topics.filter((t) => t.status === "COMPLETED").length,
            0
          );

          return (
            <div
              key={course.id}
              className="flex flex-col justify-between rounded-3xl border border-slate-200/90 bg-white p-6 shadow-sm hover:shadow-xl hover:border-sky-300 transition-all group"
            >
              <div>
                <div className="flex items-center justify-between mb-3">
                  <span className="rounded-full bg-sky-50 px-2.5 py-0.5 text-[10px] font-bold text-sky-700 border border-sky-200">
                    {course.category}
                  </span>
                  <span className="text-[10px] font-bold text-slate-400 font-mono">
                    {course.skillLevel}
                  </span>
                </div>

                <h3 className="text-lg font-bold text-slate-900 group-hover:text-sky-600 transition-colors">
                  {course.title}
                </h3>
                <p className="mt-2 text-xs text-slate-600 leading-relaxed line-clamp-2">
                  {course.description}
                </p>

                {/* Progress stats */}
                <div className="mt-5 space-y-2">
                  <div className="flex justify-between text-xs font-semibold text-slate-600">
                    <span>
                      {completedTopics} of {totalTopics} topics completed
                    </span>
                    <span className="text-sky-600 font-bold">{course.completionPct}%</span>
                  </div>
                  <div className="h-2 w-full rounded-full bg-slate-100 overflow-hidden">
                    <div
                      className="h-full bg-gradient-to-r from-sky-500 to-blue-600 rounded-full transition-all"
                      style={{ width: `${course.completionPct}%` }}
                    />
                  </div>
                </div>

                <div className="mt-4 flex items-center gap-4 text-[11px] text-slate-500">
                  <span className="flex items-center gap-1">
                    <Clock className="h-3.5 w-3.5 text-slate-400" />
                    {course.estimatedHours} Hours Total
                  </span>
                  <span>•</span>
                  <span>{course.modules.length} Modules</span>
                </div>
              </div>

              <div className="mt-6 pt-4 border-t border-slate-100 flex items-center justify-between">
                <Link
                  href={`/courses/${course.id}`}
                  className="inline-flex items-center gap-1.5 text-xs font-bold text-sky-600 hover:text-sky-700"
                >
                  <span>Open Learning Dashboard</span>
                  <ArrowRight className="h-3.5 w-3.5" />
                </Link>

                <Link
                  href={`/quizzes`}
                  className="rounded-lg border border-slate-200 px-3 py-1 text-[11px] font-semibold text-slate-600 hover:bg-slate-50"
                >
                  Diagnostic Quiz
                </Link>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
